"""ETL data contract.

The ETL only talks to these interfaces. Each source (mock, public, official)
implements the three; switching source does not change the rest of the feature.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable, Protocol


@dataclass
class Position:
    """A rover stop (row of the `waypoints` table)."""

    rmc: str            # "site_drive", e.g. "118_2028"
    site: int
    drive: int
    sol: int | None
    lat: float          # planetocentric, degrees
    lon: float          # east positive, 0–360
    elev: float | None
    yaw: float | None   # heading of the rover front, 0–360 from north
    source: str         # "mmgis" | "places" | "mock"


@dataclass
class PanoMeta:
    """A Navcam panorama (row of the `panoramas` table, before the position)."""

    id: str
    sol: int
    site: int
    drive: int
    center_az: float        # azimuth of the image center, from north
    image: str              # local path or URL of the original file
    page_url: str = ""
    credit: str = "NASA/JPL-Caltech"
    date: str = ""          # Earth capture date (ISO), if known


@dataclass
class PhotoMeta:
    """A static Navcam photo (row of the `photos` table, before the position)."""

    id: str
    instrument: str
    sol: int
    site: int
    drive: int
    date_taken: str
    mast_az: float          # measured from the rover front (M6)
    mast_el: float
    image: str              # URL or path of the JPG
    credit: str = "NASA/JPL-Caltech"
    source: str = ""


@dataclass
class Target:
    """A science target (row of the `targets` table). The position is that of the stop."""

    id: str
    name: str
    kind: str               # drill_hole | ridge | hollow | contact | feature
    sol: int
    site: int | None
    drive: int | None
    lat: float
    lon: float
    pos_quality: str        # exact | by_sol | estimated
    why_it_matters: str = ""
    safety_note: str = ""
    blog_url: str = ""
    mastcam_path: str = ""
    mastcam_credit: str = ""
    terrain_class: str = ""
    what_was_done: str = ""     # "what was done" (blog, M8)
    what_was_done_url: str = ""


@dataclass
class Measurement:
    """A ground measurement (row of the `measurements` table)."""

    id: str
    target_id: str
    instrument: str         # APXS | ChemCam | CheMin
    sol: int
    site: int | None
    drive: int | None
    summary: str            # one sentence, generated by a fixed rule
    values_json: str        # full values
    confidence: str         # measured | mock
    source_url: str = ""
    source_file: str = ""


@dataclass
class OrbitalLabel:
    """What is seen from orbit at a point (CRISM)."""

    label: str              # e.g. "monohydrated sulfate", "no signal"
    confidence: str         # "inferred from orbit" | "context" | "mock"
    note: str               # scale caveat
    source_url: str = ""
    source_name: str = ""


class PositionSource(Protocol):
    def locate(self, site: int, drive: int, sol: int | None) -> Position | None: ...

    def list_stops(self, sol_min: int, sol_max: int) -> Iterable[Position]: ...


class PanoSource(Protocol):
    def list_panoramas(self, sol_min: int, sol_max: int) -> Iterable[PanoMeta]: ...


class PhotoSource(Protocol):
    def list_photos(self, sol_min: int, sol_max: int, stops: list[Position]) -> Iterable[PhotoMeta]: ...


class ScienceSource(Protocol):
    def list_targets(self, stops: list[Position]) -> Iterable[Target]: ...

    def list_measurements(self, sol_min: int, sol_max: int) -> Iterable[Measurement]: ...


class OrbitalMineralSource(Protocol):
    def sample(self, lat: float, lon: float) -> OrbitalLabel | None: ...
