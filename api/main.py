@app.get("/api/insolation")
def get_insolation(hour: float = Query(9.0, ge=0, le=24), sol: int | None = None,
                   lat: float | None = None, lon: float | None = None):
    """Sun position and maximum direct irradiance (no dust) for a sol/local solar
    hour; with lat/lon, also shade and incidence at that point. Inferred from the relief."""
    sol = sol if sol is not None else sol_msl(now())
    if lat is not None and lon is not None:
        p = insolation_at_point(sol, round(hour * 4) / 4, lat, lon)
        if p is None:
            raise HTTPException(status_code=404, detail="Point outside the 1 m DTM")
        return p
    return sun_at_hour(sol, round(hour * 4) / 4)


@app.get("/tiles/{layer_name}/{z}/{x}/{y}.png")
def get_tile(layer_name: str, z: int, x: int, y: int, hour: float | None = Query(None, ge=0, le=24), sol: int | None = None):
    """Real standard XYZ tile -- replaces the single-image ImageSource
    (see /mosaics/{layer}.png and mosaics.py) for continuous zoom/pan
    of a real map. See tile_server.py to understand why this does not
    need real cartographic reprojection."""
    conn = get_connection()
    try:
        row = conn.execute(
            "SELECT local_tile_path, access_type, min_lon, min_lat, max_lon, max_lat FROM raster_registry WHERE layer_name = ?",
            (layer_name,),
        ).fetchone()
    finally:
        conn.close()

    if row is None:
        raise HTTPException(status_code=404, detail="Layer not found")

    bbox = (row["min_lon"], row["min_lat"], row["max_lon"], row["max_lat"])
    variant = None
    if row["access_type"] == "derived_insolation":
        # hour in quarter hours: limits how many grids stay in cache
        variant = (sol if sol is not None else sol_msl(now()), round((hour if hour is not None else 9.0) * 4) / 4)
    png_bytes = render_tile(layer_name, z, x, y, row["local_tile_path"], row["access_type"], bbox, variant)
    if png_bytes is None:
        raise HTTPException(status_code=404, detail="Tile outside the real coverage of this layer")

    return Response(content=png_bytes, media_type="image/png")


@app.get("/api/route")
def get_route(
    origin_lat: float,
    origin_lon: float,
    dest_lat: float,
    dest_lon: float,
    stop_lat: list[float] = Query(default=[]),
    stop_lon: list[float] = Query(default=[]),
):
    """Feature 02 -- real A* over the DTM, two variants (safest/
    fastest). See route_planning.py for the deliberate AI4Mars deviation
    (it does not cover the boxwork -- the cost uses only real slope, sand becomes a
    text warning). Real radiation dose (RAD, same REFERENCE_SOL as
    /api/conditions) enters as an accumulated estimate over the duration of the
    walk -- None if the sol is not cached, never a faked 0.

    stop_lat/stop_lon (same length, same order): intermediate stops
    between origin and destination -- "intermediate stops" gap."""
    if len(stop_lat) != len(stop_lon):
        raise HTTPException(status_code=422, detail="stop_lat and stop_lon must have the same length")
    stops = list(zip(stop_lat, stop_lon))

    rad_data = get_cached_conditions(REFERENCE_SOL)
    rad_dose_ugy_per_hour = rad_data["rad"]["mean_dose_ugy_per_hour"] if rad_data else None

    conn = get_connection()
    try:
        result = plan_route(conn, origin_lat, origin_lon, dest_lat, dest_lon, rad_dose_ugy_per_hour, stops)
    except OutOfGridError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except NoPathError as e:
        raise HTTPException(status_code=422, detail=str(e))
    finally:
        conn.close()
    enrich_routes(result["routes"])
    # feature 02 + 08: addition -- suggested order with the why; no route leaves the list
    result["suggestion"] = suggest(result["routes"])
    return result


def enrich_routes(routes: list[dict]) -> None:
    """Predicted chance per segment (F06) and agent alerts per point (F08), on each route."""
    # feature 06: each segment gets the predicted chance and the status that considers it
    for route in routes:
        for t in route["risk_segments"]:
            risk = slope_risk(t["slope_deg"])
            t["chance_pct"] = risk["chance_pct"] if risk else None
            t["predicted_status"] = predicted_status(t["slope_status"], risk)
        route["predicted_risk_segments"] = sum(t["predicted_status"] != t["slope_status"] for t in route["risk_segments"])

    # feature 08: addition to the contract, no key above changes --
    # crosses the rover history and the return-to-base limit (same
    # rules as /api/point) with the points of each computed variant.
    # distance_m (from the start, not from the destination) comes from the same
    # elevation_profile as the chart -- it is the "in which segment" that was missing:
    # without it, the alert applied to the whole route, not to a point on it.
    for route in routes:
        alerts = route_alerts([tuple(p) for p in route["points"]])
        profile = route["elevation_profile"]
        for alert in alerts:
            alert["distance_m"] = profile[alert.pop("point_index")]["cumulative_distance_m"]
        alerts.sort(key=lambda a: a["distance_m"])
        route["alerts"] = alerts


@app.get("/api/replan")
def get_replan(lat: float, lon: float, problem: str = Query(min_length=1, max_length=500),
               dest_lat: float | None = None, dest_lon: float | None = None, current_type: str = "safest"):
    """F02 + F08: problem reported in the middle of the walk -> new options from the marked
    point (lat/lon), in the same format as /api/route. See replan.py."""
    problem_kind = classify(problem) or "other"
    destination = (dest_lat, dest_lon) if dest_lat is not None and dest_lon is not None else None
    current_route = None
    if destination:
        try:
            current = get_route(lat, lon, *destination, [], [])
            current_route = next((r["points"] for r in current["routes"] if r["type"] == current_type), current["routes"][0]["points"])
        except HTTPException:
            pass  # without the current route the obstacle has no "ahead": options come without a detour
    rad_data = get_cached_conditions(REFERENCE_SOL)
    dose = rad_data["rad"]["mean_dose_ugy_per_hour"] if rad_data else None
    conn = get_connection()
    try:
        def plan(target, kind, avoid):
            try:
                return plan_route(conn, lat, lon, *target, dose, [], kinds=(kind,), avoid=avoid)["routes"][0]
            except (OutOfGridError, NoPathError) as e:
                raise HTTPException(status_code=422, detail=str(e))
        res = replan_options(problem_kind, (lat, lon), destination, BASE_LAT_LON, current_route, plan)
    finally:
        conn.close()
    if not res["routes"]:
        raise HTTPException(status_code=422, detail="No option with a path: " + "; ".join(res["errors"]))
    enrich_routes(res["routes"])
    return {"problem": problem_kind, "problem_text": res["text"], "obstacle": res["obstacle"],
            "routes": res["routes"], "suggestion": suggest(res["routes"]), "warnings": res["errors"]}


@app.get("/api/route-forecast")
def get_route_forecast(origin_lat: float, origin_lon: float, dest_lat: float, dest_lon: float,
                       type: str = "safest", sol: int | None = None):
    """Agent tool: predictive analysis of the route (terrain from Curiosity
    history, climate and window on the EVA sol, forecast dose). See route_forecast.py."""
    if type not in ("safest", "fastest", "most_science"):  # smoothest (replanning option)
        type = "safest"  # shortcut: forecast from the safest, without the detour; pass kinds/avoid if they diverge a lot
    result = get_route(origin_lat, origin_lon, dest_lat, dest_lon, [], [])
    route = next((r for r in result["routes"] if r["type"] == type), None)
    if route is None:
        raise HTTPException(status_code=404, detail=f"Variant {type!r} does not exist for these points")
    return {**forecast_route(route, sol if sol is not None else sol_msl(now())),
            "suggestion": result["suggestion"]}


