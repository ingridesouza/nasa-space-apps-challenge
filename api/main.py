@app.middleware("http")
async def front_always_revalidated(request: Request, call_next):
    """Front (web/) with Cache-Control: no-cache -- the browser revalidates on each load
    (cheap 304, it is local). Without this, after updating the system it mixes old JS
    modules from the cache with new ones and the page does not come up."""
    resp = await call_next(request)
    if request.url.path == "/" or request.url.path.endswith((".js", ".mjs", ".css", ".html")):
        resp.headers["Cache-Control"] = "no-cache"
    return resp


@app.get("/api/point")
def get_point(lat: float, lon: float, request: Request):
    """Combines vector search (nearby photos, science target) and
    raster sampling (elevation/slope) at a single point -- contract
    reused by feature 02 (route/A*) and feature 08 (voice)."""
    conn = get_connection()
    try:
        photos = nearby_photos(conn, lat, lon, base_url=str(request.base_url).rstrip("/"))
        target = nearest_science_target(conn, lat, lon)
        rasters = sample_all_rasters(conn, lat, lon)
        thermal = inertia_at_point(conn, lat, lon)
    finally:
        conn.close()

    return {
        "point": {"lat": lat, "lon": lon},
        "nearby_photos": photos,
        "science_target": target,
        "raster_values": rasters,
        # feature 08: addition to the contract, no key above changed
        "alerts": point_alerts(lat, lon, rasters),
        # feature 06: chance that the real terrain exceeds 15°, from the rover history
        "slope_forecast": slope_risk(rasters.get("slope_deg")),
        # THEMIS thermal inertia (100 m): addition to the contract
        "thermal_inertia": thermal,
    }


