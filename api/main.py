@app.get("/api/rover-track")
def get_rover_track():
    """Curiosity stops inside the layers' bbox, with the slope
    measured by the rover already classified (feature 08, terrain memory).
    The bbox comes from raster_registry, the same single source as /layers.

    Real bug fixed: it was MIN(min)/MAX(max) -- the UNION of the bboxes of
    all layers, dominated by THEMIS (it covers a much larger area
    than the CTX/HiRISE/DTM actually downloaded). That let real
    rover stops outside any base image through, so the
    track appeared over a black background when zooming out. The right one is the
    INTERSECTION (MAX(min)/MIN(max)): only the area where every layer has
    real data."""
    conn = get_connection()
    try:
        bbox = conn.execute(
            "SELECT MAX(min_lon), MAX(min_lat), MIN(max_lon), MIN(max_lat) FROM raster_registry"
        ).fetchone()
    finally:
        conn.close()

    stops = stops_in_bbox(*bbox) if bbox[0] is not None else None
    if stops is None:
        raise HTTPException(
            status_code=404,
            detail="Track not available -- run data-pipeline/scripts/fetch_rover_waypoints.py and populate_raster_registry.py",
        )
    return stops


