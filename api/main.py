@app.get("/api/rover-track")
def get_rover_track():
    """Curiosity stops inside the layers' bbox, with the slope
    measured by the rover already classified (feature 08, terrain memory).
    The bbox comes from raster_registry, the same single source as /layers.

    Real bug fixed: it was MIN(min)/MAX(max) -- the UNION of the bboxes of
    all layers, dominated by THEMIS (it covers a much larger area
    than the CTX/HiRISE/DTM actually downloaded). That let real
    rover stops outside any base image through, so the
    track appeared over a black background when zooming out. The right one is the
    INTERSECTION (MAX(min)/MIN(max)): only the area where every layer has
    real data."""
    conn = get_connection()
    try:
        bbox = conn.execute(
            "SELECT MAX(min_lon), MAX(min_lat), MIN(max_lon), MIN(max_lat) FROM raster_registry"
        ).fetchone()
    finally:
        conn.close()

    stops = stops_in_bbox(*bbox) if bbox[0] is not None else None
    if stops is None:
        raise HTTPException(
            status_code=404,
            detail="Track not available -- run data-pipeline/scripts/fetch_rover_waypoints.py and populate_raster_registry.py",
        )
    return stops


@app.get("/api/atmosphere/track")
def get_atmosphere_track():
    """Atmospheric layer: REMS measured on each sol, at the rover's last stop
    on that sol (GeoJSON). Sols without data in the PDS come with null values."""
    conn = get_connection()
    try:
        bbox = conn.execute(
            "SELECT MAX(min_lon), MAX(min_lat), MIN(max_lon), MIN(max_lat) FROM raster_registry"
        ).fetchone()
    finally:
        conn.close()
    geo = track_geojson(stops_in_bbox(*bbox) if bbox[0] is not None else None)
    if geo is None:
        raise HTTPException(status_code=404, detail="No atmospheric cache -- run data-pipeline/scripts/cache_atmosphere_track.py")
    return geo


@app.get("/api/clock")
def get_clock():
    """Simulated mission clock: sol and local solar time at Gale now.
    Configurable with H2G2_CLOCK="SOL@HH:MM"; runs in real time."""
    t = now()
    return {**local_time(t), "utc": t.isoformat(), "simulated": True,
            "source": "simulated clock (H2G2_CLOCK) + Mars24 (LMST, equation of time)"}


@app.get("/api/insolation")
def get_insolation(hour: float = Query(9.0, ge=0, le=24), sol: int | None = None,
                   lat: float | None = None, lon: float | None = None):
    """Sun position and maximum direct irradiance (no dust) for a sol/local solar
    hour; with lat/lon, also shade and incidence at that point. Inferred from the relief."""
    sol = sol if sol is not None else sol_msl(now())
    if lat is not None and lon is not None:
        p = insolation_at_point(sol, round(hour * 4) / 4, lat, lon)
        if p is None:
            raise HTTPException(status_code=404, detail="Point outside the 1 m DTM")
        return p
    return sun_at_hour(sol, round(hour * 4) / 4)


@app.get("/tiles/{layer_name}/{z}/{x}/{y}.png")
def get_tile(layer_name: str, z: int, x: int, y: int, hour: float | None = Query(None, ge=0, le=24), sol: int | None = None):
    """Real standard XYZ tile -- replaces the single-image ImageSource
    (see /mosaics/{layer}.png and mosaics.py) for continuous zoom/pan
    of a real map. See tile_server.py to understand why this does not
    need real cartographic reprojection."""
    conn = get_connection()
    try:
        row = conn.execute(
            "SELECT local_tile_path, access_type, min_lon, min_lat, max_lon, max_lat FROM raster_registry WHERE layer_name = ?",
            (layer_name,),
        ).fetchone()
    finally:
        conn.close()

    if row is None:
        raise HTTPException(status_code=404, detail="Layer not found")

    bbox = (row["min_lon"], row["min_lat"], row["max_lon"], row["max_lat"])
    variant = None
    if row["access_type"] == "derived_insolation":
        # hour in quarter hours: limits how many grids stay in cache
        variant = (sol if sol is not None else sol_msl(now()), round((hour if hour is not None else 9.0) * 4) / 4)
    png_bytes = render_tile(layer_name, z, x, y, row["local_tile_path"], row["access_type"], bbox, variant)
    if png_bytes is None:
        raise HTTPException(status_code=404, detail="Tile outside the real coverage of this layer")

    return Response(content=png_bytes, media_type="image/png")


@app.get("/api/route")
def get_route(
    origin_lat: float,
    origin_lon: float,
    dest_lat: float,
    dest_lon: float,
    stop_lat: list[float] = Query(default=[]),
    stop_lon: list[float] = Query(default=[]),
):
    """Feature 02 -- real A* over the DTM, two variants (safest/
    fastest). See route_planning.py for the deliberate AI4Mars deviation
    (it does not cover the boxwork -- the cost uses only real slope, sand becomes a
    text warning). Real radiation dose (RAD, same REFERENCE_SOL as
    /api/conditions) enters as an accumulated estimate over the duration of the
    walk -- None if the sol is not cached, never a faked 0.

    stop_lat/stop_lon (same length, same order): intermediate stops
    between origin and destination -- "intermediate stops" gap."""
    if len(stop_lat) != len(stop_lon):
        raise HTTPException(status_code=422, detail="stop_lat and stop_lon must have the same length")
    stops = list(zip(stop_lat, stop_lon))

    rad_data = get_cached_conditions(REFERENCE_SOL)
    rad_dose_ugy_per_hour = rad_data["rad"]["mean_dose_ugy_per_hour"] if rad_data else None

    conn = get_connection()
    try:
        result = plan_route(conn, origin_lat, origin_lon, dest_lat, dest_lon, rad_dose_ugy_per_hour, stops)
    except OutOfGridError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except NoPathError as e:
        raise HTTPException(status_code=422, detail=str(e))
    finally:
        conn.close()
    # feature 06: each segment gets the predicted chance and the status that considers it
    for route in result["routes"]:
        for t in route["risk_segments"]:
            risk = slope_risk(t["slope_deg"])
            t["chance_pct"] = risk["chance_pct"] if risk else None
            t["predicted_status"] = predicted_status(t["slope_status"], risk)
        route["predicted_risk_segments"] = sum(t["predicted_status"] != t["slope_status"] for t in route["risk_segments"])

    # feature 08: addition to the contract, no key above changes --
    # crosses the rover history and the return-to-base limit (same
    # rules as /api/point) with the points of each computed variant.
    # distance_m (from the start, not from the destination) comes from the same
    # elevation_profile as the chart -- it is the "in which segment" that was missing:
    # without it, the alert applied to the whole route, not to a point on it.
    for route in result["routes"]:
        alerts = route_alerts([tuple(p) for p in route["points"]])
        profile = route["elevation_profile"]
        for alert in alerts:
            alert["distance_m"] = profile[alert.pop("point_index")]["cumulative_distance_m"]
        alerts.sort(key=lambda a: a["distance_m"])
        route["alerts"] = alerts

    return result


class Question(BaseModel):
    question: str = Field(min_length=1, max_length=500)
    # with no chosen point, the assistant answers about the base (same as api/alerts.py)
    lat: float = Field(BASE_LAT_LON[0], ge=-90, le=90)
    lon: float = Field(BASE_LAT_LON[1], ge=-180, le=360)
    sol: int = REFERENCE_SOL


@app.post("/api/ask")
def ask(q: Question, request: Request):
    """Feature 08, phase 2: natural-language question about the point,
    answered by the local model using only the /api/point context."""
    point = get_point(q.lat, q.lon, request)
    conditions = get_cached_conditions(q.sol)
    if conditions:
        conditions["time"], conditions["alerts"] = sol_time_and_alerts(q.sol)
        conditions["today_forecast"] = sol_forecast(conditions["time"]["sol_now"])
    ctx = build_context(point, conditions)
    try:
        answer = ask_agent(q.question, ctx)
    except AgentUnavailable as e:
        # 503 with the alerts: the safety rules do not depend on the model
        raise HTTPException(status_code=503, detail={"message": str(e), "alerts": point["alerts"]})
    # Danger is stated by rule, before the answer: the 3B model sometimes omits it.
    dangers = " ".join(a["message"] for a in point["alerts"] if a["level"] == "danger")
    if dangers:
        answer = f"Danger: {dangers} {answer}"
    return {"answer": answer, "sources": context_sources(ctx), "alerts": point["alerts"]}


@app.get("/api/forecast")
def get_forecast(sol: int | None = None, duration_min: float | None = Query(None, gt=0, le=24 * 60)):
    """Feature 06: forecast climate for a sol (default: today's), offline.
    Estimate with a band and an error measured by backtest -- it never becomes "measured".
    With duration_min (route time), suggests the best window of the day for the EVA."""
    fc = sol_forecast(sol if sol is not None else sol_msl(now()), duration_min)
    if fc is None:
        raise HTTPException(status_code=404, detail="No climatology: run data-pipeline/scripts/cache_climatology.py")
    return fc


class Measurement(BaseModel):
    """Habitat/suit sensor reading (feature 06): Gale physical ranges with margin."""
    sol: int = Field(ge=1, le=20000)
    temp_min_c: float = Field(ge=-150, le=40)
    temp_max_c: float = Field(ge=-150, le=60)
    pressure_pa: float = Field(ge=100, le=1500)
    ground_noon_c: float | None = Field(None, ge=-150, le=80)
    dose_ugy_day: float | None = Field(None, ge=0, le=100000)


@app.post("/api/measurement")
def post_measurement(m: Measurement):
    if m.temp_min_c > m.temp_max_c:
        raise HTTPException(status_code=422, detail="temp_min_c greater than temp_max_c")
    return record_measurement(m.model_dump())


@app.delete("/api/measurement/{sol}")
def delete_measurement_endpoint(sol: int):
    if not delete_measurement(sol):
        raise HTTPException(status_code=404, detail=f"No local measurement on sol {sol}")
    return {"deleted": sol}


