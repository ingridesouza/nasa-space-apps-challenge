@app.get("/mosaics/{layer_name}.png")
def get_mosaic(layer_name: str):
    """Single image to display a layer on the map -- tile stitch
    (`tiles_wmts`) or hillshade generated on the fly from a DTM
    (`derived_hillshade`). See mosaics.py to understand why this
    replaces a standard MapLibre XYZ `tiles` source (our Mars Trek
    tile grid is not Web Mercator)."""
    conn = get_connection()
    try:
        row = conn.execute(
            "SELECT local_tile_path, access_type FROM raster_registry WHERE layer_name = ?",
            (layer_name,),
        ).fetchone()
    finally:
        conn.close()

    if row is None:
        raise HTTPException(status_code=404, detail="Layer not found")

    if row["access_type"] == "derived_hillshade":
        png_bytes = build_hillshade_png(row["local_tile_path"])
    elif row["access_type"] == "tiles_wmts":
        png_bytes = build_mosaic_png(row["local_tile_path"], thermal_palette=(layer_name == "themis_thermal"))
    else:
        raise HTTPException(status_code=404, detail=f"access_type {row['access_type']!r} does not become a mosaic")

    if png_bytes is None:
        raise HTTPException(status_code=404, detail="Local data not found for this layer")

    return Response(content=png_bytes, media_type="image/png")


