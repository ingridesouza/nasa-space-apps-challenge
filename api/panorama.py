"""F03 · panorama and photos at the point (+ orbital crop and map window).

Reads the `waypoints`, `panoramas`, `photos` tables from the single database
(data/local/h2g2.sqlite) and the files in data/local/f03/ served at /bundle,
all generated by data-pipeline/f03/etl/build.py (`make build`).
"""

from __future__ import annotations

import io
import json
import sqlite3
import threading
from functools import lru_cache
from pathlib import Path

import yaml
from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import Response
from PIL import Image, ImageDraw

from db import DB_PATH
from geo import bbox, bearing, compass, haversine, initial_yaw

F03_PIPELINE = Path(__file__).resolve().parent.parent / "data-pipeline" / "f03"
CFG = yaml.safe_load((F03_PIPELINE / "config.yaml").read_text(encoding="utf-8"))
BUNDLE = (F03_PIPELINE / CFG["paths"]["bundle"]).resolve()
R_PANO = CFG["radius_m"]["panorama"]
R_PHOTO = CFG["radius_m"]["photos"]
PHOTO_LIMIT = CFG["photos"]["limit"]
CROP_M = CFG["orbital_crop_m"]
R_CARD = CFG["card_radius_m"]

Image.MAX_IMAGE_PIXELS = None
router = APIRouter()


_local = threading.local()


def _connection() -> sqlite3.Connection:
    # one connection per thread: FastAPI runs sync routes in parallel, and a
    # shared connection mixes up the cursors (empty query -> false 503)
    con = getattr(_local, "con", None)
    if con is None:
        con = _local.con = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
        con.row_factory = sqlite3.Row
    return con


def db() -> sqlite3.Connection:
    """Read-only connection to the single database; 503 if the F03 ETL has not run yet."""
    if not Path(DB_PATH).exists() or not _connection().execute(
            "SELECT 1 FROM sqlite_master WHERE name = 'panoramas'").fetchone():
        raise HTTPException(503, "F03/F04 data not found: run `make build`.")
    return _connection()


@lru_cache(maxsize=1)
def map_info() -> dict:
    p = BUNDLE / "map.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


# --------------------------------------------------------------------------- #
# Text utilities (interface honesty rules)
# --------------------------------------------------------------------------- #


def fmt_dist(d: float) -> str:
    """Rounded to 10 m, always with '~'."""
    return "less than 10 m" if d < 5 else f"~{int(round(d / 10.0) * 10)} m"


def fmt_date(iso: str | None) -> str:
    if not iso or len(iso) < 10:
        return ""
    return f" ({iso[:10]})"


def norm_point(lat: float, lon: float) -> tuple[float, float, bool]:
    """Negative longitude becomes 0–360; says whether the point is inside the window."""
    lon = lon % 360
    w = map_info().get("window") or CFG["window"]
    inside = w["lat_min"] <= lat <= w["lat_max"] and w["lon_min"] <= lon <= w["lon_max"]
    return lat, lon, inside


def candidates(table: str, tree: str, lat: float, lon: float, radius: float):
    """R-tree by the box in degrees, then exact haversine and the d ≤ r filter."""
    lo0, lo1, la0, la1 = bbox(lat, lon, radius)
    rows = db().execute(
        f"SELECT t.* FROM {table} t JOIN {tree} r ON t.rowid = r.rid "
        "WHERE r.min_lon <= ? AND r.max_lon >= ? AND r.min_lat <= ? AND r.max_lat >= ?",
        (lo1, lo0, la1, la0),
    ).fetchall()
    out = []
    for r in rows:
        d = haversine(lat, lon, r["lat"], r["lon"])
        if d <= radius:
            out.append((d, r))
    # distance tie (same stop): the color Mastcam comes first
    out.sort(key=lambda x: (round(x[0], 3), "camera" in x[1].keys() and x[1]["camera"] != "Mastcam", x[1]["sol"]))
    return out


