@router.get("/map")
def get_map():
    return map_info()


@router.get("/panoramas/nearest")
def panorama_nearest(lat: float = Query(..., ge=-90, le=90), lon: float = Query(...),
                     radius: float = Query(R_PANO, gt=0, le=5000)):
    lat, lon, inside = norm_point(lat, lon)
    found = candidates("panoramas", "pano_rtree", lat, lon, radius)
    if not found:
        return {"found": False, "inside_window": inside,
                "message": f"no panorama within {int(radius)} m"}
    d, p = found[0]
    bearing_point_stop = bearing(lat, lon, p["lat"], p["lon"])
    bearing_stop_point = bearing(p["lat"], p["lon"], lat, lon)
    yaw = 0.0 if d < 1 else initial_yaw(bearing_stop_point, p["center_az"])
    color = p["camera"] == "Mastcam"
    suffix = "Mastcam · color · estimated position" if color else "Navcam"
    label = (f"panorama taken {fmt_dist(d)} from the destination, to the {compass(bearing_point_stop)}"
             f" · sol {p['sol']}{fmt_date(p['date'])} · {suffix}")
    return {
        "found": True, "inside_window": inside,
        "id": p["id"], "sol": p["sol"], "date": p["date"], "rmc": f"{p['site']}_{p['drive']}",
        "lat": p["lat"], "lon": p["lon"], "distance_m": round(d, 1),
        "bearing_point_to_stop": round(bearing_point_stop, 1),
        "bearing_stop_to_point": round(bearing_stop_point, 1),
        "label": label, "credit": p["credit"], "page_url": p["page_url"],
        "pos_quality": p["pos_quality"],
        "pannellum": {"type": "equirectangular", "panorama": f"/bundle/{p['img_path']}",
                      "haov": p["haov"], "vaov": p["vaov"], "vOffset": p["voffset"],
                      "northOffset": p["center_az"], "yaw": round(yaw, 2), "pitch": 0,
                      "hfov": 90, "autoLoad": True, "compass": True},
    }


@router.get("/photos/near")
def photos_near(lat: float = Query(..., ge=-90, le=90), lon: float = Query(...),
                radius: float = Query(R_PHOTO, gt=0, le=5000),
                limit: int = Query(PHOTO_LIMIT, gt=0, le=100)):
    lat, lon, inside = norm_point(lat, lon)
    found = candidates("photos", "photo_rtree", lat, lon, radius)[:limit]
    photos, stops = [], {}
    for d, r in found:
        rmc = f"{r['site']}_{r['drive']}"
        brg = bearing(lat, lon, r["lat"], r["lon"])
        looking = f", looking {compass(r['true_az'])}" if r["true_az"] is not None else ""
        photos.append({
            "id": r["id"], "rmc": rmc, "sol": r["sol"], "date_taken": r["date_taken"],
            "instrument": r["instrument"], "distance_m": round(d, 1),
            "true_azimuth": None if r["true_az"] is None else round(r["true_az"], 1),
            "mast_el": r["mast_el"], "img": f"/bundle/{r['img_path']}",
            "thumb": f"/bundle/{r['thumb_path']}", "credit": r["credit"],
            "label": (f"photo taken {fmt_dist(d)} from the destination, to the {compass(brg)}{looking}"
                      f" · sol {r['sol']}{fmt_date(r['date_taken'])} · Navcam"),
        })
        stops.setdefault(rmc, []).append(r["id"])
    return {"inside_window": inside, "total": len(photos), "photos": photos,
            "by_stop": [{"rmc": k, "photos": v} for k, v in stops.items()]}


@lru_cache(maxsize=1)
def _orbital_image():
    o = map_info().get("orbital")
    if not o:
        return None, None
    return Image.open(BUNDLE / o["image"]).convert("RGB"), o


@router.get("/orbital/crop")
def orbital_crop(lat: float = Query(..., ge=-90, le=90), lon: float = Query(...)):
    lat, lon, _ = norm_point(lat, lon)
    im, o = _orbital_image()
    if im is None:
        raise HTTPException(404, "Orbital base not included in the bundle.")
    x = (lon - o["lon_min"]) / (o["lon_max"] - o["lon_min"]) * im.width
    y = (o["lat_max"] - lat) / (o["lat_max"] - o["lat_min"]) * im.height
    if not (0 <= x < im.width and 0 <= y < im.height):
        raise HTTPException(404, "Point outside the HiRISE crop.")
    half = CROP_M / o["res_m"] / 2
    crop = im.crop((int(x - half), int(y - half), int(x + half), int(y + half)))
    dr = ImageDraw.Draw(crop)
    c = crop.width / 2
    for a, b in (((c - 12, c), (c - 4, c)), ((c + 4, c), (c + 12, c)),
                 ((c, c - 12), (c, c - 4)), ((c, c + 4), (c, c + 12))):
        dr.line((a, b), fill=(255, 230, 0), width=2)
    buf = io.BytesIO()
    crop.save(buf, "PNG")
    return Response(buf.getvalue(), media_type="image/png",
                    headers={"X-Credit": "NASA/JPL/University of Arizona/USGS",
                             "X-Side-m": str(CROP_M)})
