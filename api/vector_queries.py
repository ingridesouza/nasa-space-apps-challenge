"""Vector queries for /api/point (feature 01, section 3.2, steps 1-2),
/api/photos and the "most science" route.

Single source: the F03/F04 tables in the local database (`photos`, `targets`,
`measurements`), generated by data-pipeline/f03/etl/build.py. The response
keys are those of the /api/point contract -- do not rename."""

import sqlite3

from geo import bbox_radius_degrees, bearing_cardinal, haversine_m


def _photo_url(img_path: str, base_url: str) -> str:
    """Local file of the F03 bundle, served at /bundle by the API itself."""
    return f"{base_url}/bundle/{img_path}"


def all_photos(conn: sqlite3.Connection, base_url: str) -> list[dict]:
    """All photos with a real position -- used by the "rover trail"
    layer on the map (clickable pins at the real positions where each photo
    was taken), unlike nearby_photos, which is by radius around
    a click."""
    rows = conn.execute(
        "SELECT lat, lon, sol, instrument, img_path FROM photos WHERE img_path != '' ORDER BY sol, id"
    ).fetchall()
    return [
        {
            "lat": r["lat"],
            "lon": r["lon"],
            "sol": r["sol"],
            "camera": r["instrument"],
            "url": _photo_url(r["img_path"], base_url),
        }
        for r in rows
    ]


def nearby_photos(conn: sqlite3.Connection, lat: float, lon: float, base_url: str, radius_m: float = 200) -> list[dict]:
    dlat, dlon = bbox_radius_degrees(lat, radius_m)

    candidates = conn.execute(
        """
        SELECT photos.*
        FROM photo_rtree
        JOIN photos ON photos.rowid = photo_rtree.rid
        WHERE photo_rtree.min_lon <= ? AND photo_rtree.max_lon >= ?
          AND photo_rtree.min_lat <= ? AND photo_rtree.max_lat >= ?
          AND photos.img_path != ''
        """,
        (lon + dlon, lon - dlon, lat + dlat, lat - dlat),
    ).fetchall()

    result = []
    for photo in candidates:
        distance = haversine_m(lat, lon, photo["lat"], photo["lon"])
        if distance <= radius_m:
            result.append(
                {
                    "distance_m": round(distance),
                    "bearing": bearing_cardinal(lat, lon, photo["lat"], photo["lon"]),
                    "sol": photo["sol"],
                    "camera": photo["instrument"],
                    "url": _photo_url(photo["img_path"], base_url),
                }
            )

    result.sort(key=lambda f: f["distance_m"])
    return result


def _measurements_as_text(conn: sqlite3.Connection, target_id: str) -> tuple[str | None, str | None]:
    """Summary of the target's measurements ("APXS: ... · CheMin: ...") and the URL of the
    first source. (None, None) if the target has no published measurement."""
    meds = conn.execute(
        "SELECT instrument, summary, source_url FROM measurements WHERE target_id = ? ORDER BY instrument",
        (target_id,),
    ).fetchall()
    if not meds:
        return None, None
    return " · ".join(f"{m['instrument']}: {m['summary']}" for m in meds), meds[0]["source_url"]


def all_science_targets(conn: sqlite3.Connection) -> list[dict]:
    """Targets for the "most science" route: name, lat, lon, curiosity_measurement, source_url."""
    targets = []
    for t in conn.execute("SELECT id, name, lat, lon, blog_url FROM targets").fetchall():
        measurement, source = _measurements_as_text(conn, t["id"])
        targets.append({"name": t["name"], "lat": t["lat"], "lon": t["lon"],
                        "curiosity_measurement": measurement, "source_url": source or t["blog_url"]})
    return targets


def nearest_science_target(conn: sqlite3.Connection, lat: float, lon: float, max_radius_m: float = 500) -> dict | None:
    dlat, dlon = bbox_radius_degrees(lat, max_radius_m)

    candidates = conn.execute(
        """
        SELECT targets.*
        FROM target_rtree
        JOIN targets ON targets.rowid = target_rtree.rid
        WHERE target_rtree.min_lon <= ? AND target_rtree.max_lon >= ?
          AND target_rtree.min_lat <= ? AND target_rtree.max_lat >= ?
        """,
        (lon + dlon, lon - dlon, lat + dlat, lat - dlat),
    ).fetchall()

    best = None
    smallest_distance = None
    for target in candidates:
        distance = haversine_m(lat, lon, target["lat"], target["lon"])
        if distance <= max_radius_m and (smallest_distance is None or distance < smallest_distance):
            smallest_distance = distance
            best = target

    if best is None:
        return None

    measurement, source = _measurements_as_text(conn, best["id"])
    return {
        "name": best["name"],
        "crism_mineral": None,  # per-pixel CRISM comes in the card (/science/card, "orbit" section)
        "terrain_class": best["terrain_class"] or None,
        "curiosity_measurement": measurement,
        "confidence": "measured" if measurement else "context",
        "source": source or best["blog_url"],
        "distance_m": round(smallest_distance),
    }
