"""Reads the conditions summary (REMS+RAD) already cached in
data/local/conditions/sol_<n>.json -- generated by
data-pipeline/scripts/cache_conditions.py. No network call here:
runs 100% offline, like the rest of the project."""

import json
import os

CONDITIONS_DIR = os.path.join(os.path.dirname(__file__), "..", "data", "local", "conditions")


def get_cached_conditions(sol: int) -> dict | None:
    path = os.path.join(CONDITIONS_DIR, f"sol_{sol}.json")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)
