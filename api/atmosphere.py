"""Atmospheric layer: what REMS measured on each sol, at the point where the rover
was (last stop of the sol). Reads data/local/conditions/atmosphere_track.json,
generated by data-pipeline/scripts/cache_atmosphere_track.py. No network here.

It is not a map of the air: REMS measures only where the rover is. The difference
between two points mixes place and time (season, Ls). Temperature varies almost only
with the season; pressure varies with the season and with elevation (~10% per ~1 km)."""

import json
import os
from functools import lru_cache

from mars_time import sol_date

FILE = os.path.join(os.path.dirname(__file__), "..", "data", "local", "conditions", "atmosphere_track.json")

#: variable -> (label, unit); the order is the selector order in the front
VARIABLES = {
    "temp_max_c": ("Max. air temperature", "°C"),
    "temp_min_c": ("Min. air temperature", "°C"),
    "pressure_pa": ("Mean pressure", "Pa"),
}


@lru_cache(maxsize=1)
def _cache() -> dict | None:
    if not os.path.isfile(FILE):
        return None
    with open(FILE, encoding="utf-8") as f:
        return json.load(f)


def track_geojson(stops: list[dict] | None) -> dict | None:
    """One point per measured sol. Sols with a stop in the crop but no data in the
    file (after the last sol published in the PDS, or a PDS gap) come in with the
    variables as null and the reason: never an invented value."""
    cache = _cache()
    if cache is None:
        return None
    measured = {c["sol"]: c for c in cache["sols"]}
    last_pds = cache["last_pds_sol"]

    features = []
    for c in measured.values():
        props = {"sol": c["sol"], "ls": c["ls"], "earth_date": sol_date(c["sol"]).date().isoformat(),
                 "elev_m": c["elev_m"], "confidence": "measured", **{k: c.get(k) for k in VARIABLES}}
        features.append(_point(c["lon"], c["lat"], props))

    # last stop of each sol still without data
    missing = {}
    for p in stops or []:
        if p["sol"] not in measured:
            missing[p["sol"]] = p
    for sol, p in missing.items():
        reason = "sol not yet published in the PDS" if sol > last_pds else "no REMS product in the PDS for this sol"
        props = {"sol": sol, "ls": None, "earth_date": sol_date(sol).date().isoformat(), "elev_m": None,
                 "confidence": None, "reason": reason, **{k: None for k in VARIABLES}}
        features.append(_point(p["lon"], p["lat"], props))

    features.sort(key=lambda f: f["properties"]["sol"])
    return {
        "type": "FeatureCollection",
        "features": features,
        "variables": {k: {"label": r, "unit": u} for k, (r, u) in VARIABLES.items()},
        "last_pds_sol": last_pds,
        "source": cache["source"],
        "note": "REMS measures only where the rover is: the difference between points mixes place and season (Ls).",
    }


def _point(lon: float, lat: float, props: dict) -> dict:
    return {"type": "Feature", "geometry": {"type": "Point", "coordinates": [lon, lat]}, "properties": props}
