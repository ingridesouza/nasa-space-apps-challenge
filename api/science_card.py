"""F04 · science card for the point (GET /science/card).

Reads `targets` and `measurements` from the single database and the CRISM crop
from data/local/f03/, generated by data-pipeline/f03/etl/build.py.
"""

from __future__ import annotations

import json
import sys
from functools import lru_cache

from fastapi import APIRouter, Query

from panorama import BUNDLE, CFG, F03_PIPELINE, R_CARD, candidates, db, fmt_dist, norm_point

sys.path.append(str(F03_PIPELINE))  # etl.sources: CRISM sampling, same rule as the ETL

router = APIRouter()


@lru_cache(maxsize=1)
def orbital_source():
    """F04 OrbitalMineralSource, read from the bundle; None if the source does not exist."""
    if CFG["science_source"] == "public":
        from etl.sources.science_public import PublicOrbital
        return PublicOrbital(BUNDLE / "crism_boxwork.json")
    from etl.sources import make_science_sources
    try:
        return make_science_sources(CFG["science_source"], CFG, F03_PIPELINE)[1]
    except NotImplementedError:
        return None


@lru_cache(maxsize=1)
def terrain_polygons() -> list[tuple[list, dict]]:
    """M6 polygons (terrain.geojson in the bundle): [(rings, properties)]."""
    p = BUNDLE / "terrain.geojson"
    if not p.exists():
        return []
    out = []
    for f in json.loads(p.read_text(encoding="utf-8")).get("features", []):
        g = f.get("geometry") or {}
        polys = [g["coordinates"]] if g.get("type") == "Polygon" else (
            g["coordinates"] if g.get("type") == "MultiPolygon" else [])
        out += [(rings, f.get("properties") or {}) for rings in polys]
    return out


def _in_ring(lon: float, lat: float, ring: list) -> bool:
    inside = False
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        if (y1 > lat) != (y2 > lat) and lon < x1 + (lat - y1) * (x2 - x1) / (y2 - y1):
            inside = not inside
    return inside


def terrain_at(lat: float, lon: float) -> dict | None:
    """Point-in-polygon (outer ring minus holes); longitude accepts −180–180 or 0–360."""
    for rings, props in terrain_polygons():
        for x in (lon, lon - 360):
            if _in_ring(x, lat, [c[:2] for c in rings[0]]) and not any(
                    _in_ring(x, lat, [c[:2] for c in h]) for h in rings[1:]):
                return props
    return None


CONFIDENCE_LABEL = {"measured": "measured", "mock": "example (test data)",
                    "inferred from orbit": "inferred from orbit", "context": "context"}
GAZETTEER = "https://planetarynames.wr.usgs.gov/"
KIND_LABEL = {"drill_hole": "drill hole", "ridge": "ridge", "hollow": "hollow (depression)",
              "contact": "geological contact", "feature": "feature"}


SCALE = {"APXS": "measured at this stop", "CheMin": "measured at this stop",
         "ChemCam": "measured up to ~7 m from this stop"}


def _row(section: str, text: str, confidence: str, instrument: str | None,
         source_url: str, source_file: str = "", **extra) -> dict | None:
    """Honesty rule: a row without a source does not exist."""
    if not text or not (source_url or source_file):
        return None
    return {"section": section, "text": text, "instrument": instrument,
            "confidence": confidence, "confidence_label": CONFIDENCE_LABEL.get(confidence, confidence),
            "source_url": source_url, "source_file": source_file, **extra}


@router.get("/science/card")
def science_card(lat: float = Query(..., ge=-90, le=90), lon: float = Query(...),
                 radius: float = Query(R_CARD, gt=0, le=5000)):
    lat, lon, inside = norm_point(lat, lon)
    found = candidates("targets", "target_rtree", lat, lon, radius)
    out = {"inside_window": inside, "radius_m": radius, "target": None, "rows": [],
           "context": [], "mastcam": None, "position_warning": None, "message": None}
    rows = []

    if found:
        d, t = found[0]
        out["target"] = {
            "id": t["id"], "name": t["name"], "name_label": "target name (Curiosity team)",
            "kind": t["kind"], "kind_label": KIND_LABEL.get(t["kind"], t["kind"]),
            "sol": t["sol"], "rmc": None if t["site"] is None else f"{t['site']}_{t['drive']}",
            "lat": t["lat"], "lon": t["lon"], "distance_m": round(d, 1),
            "distance_label": f"{fmt_dist(d)} from the queried point", "pos_quality": t["pos_quality"],
        }
        if t["pos_quality"] != "exact":
            out["position_warning"] = f"position approximated by the stop of sol {t['sol']}"
        meds = db().execute("SELECT * FROM measurements WHERE target_id = ? ORDER BY instrument",
                            (t["id"],)).fetchall()
        for m in meds:
            sec = "mineralogy" if m["instrument"] == "CheMin" else "chemistry"
            rows.append(_row(sec, m["summary"], m["confidence"], m["instrument"],
                             m["source_url"], m["source_file"], sol=m["sol"],
                             scale=SCALE.get(m["instrument"])))
        if not meds:
            rows.append(_row("no_measurement", "no published measurement for this target",
                             "context", None, t["blog_url"]))
        out["context"].append(_row("what_was_done", t["what_was_done"], "context",
                                   "Curiosity blog", t["what_was_done_url"]))
        for sec, txt in (("why_it_matters", t["why_it_matters"]), ("safety", t["safety_note"])):
            out["context"].append(_row(sec, txt, "context", None, t["blog_url"]))
        if t["terrain_class"]:
            rows.append(_row("terrain", t["terrain_class"], "context", "H2G2 team classification",
                             t["blog_url"]))
        # local file only (offline system): an external URL never goes into the card
        if t["mastcam_path"] and not t["mastcam_path"].startswith("http"):
            out["mastcam"] = {"img": f"/bundle/mastcam/{t['mastcam_path']}",
                              "credit": t["mastcam_credit"],
                              "label": f"Mastcam photo from sol {t['sol']}"}
    else:
        out["message"] = f"no studied target within {int(radius)} m"

    orb = orbital_source().sample(lat, lon) if inside and orbital_source() else None
    if orb:
        rows.append(_row("orbit", f"{orb.label} ({orb.note})", orb.confidence,
                         "CRISM", orb.source_url, orb.source_name))
    ter = terrain_at(lat, lon) if inside else None
    if ter and ter.get("class"):
        note = ter.get("safety_note")
        rows.append(_row("terrain", ter["class"], "context", "H2G2 team classification",
                         "", "terrain.geojson (polygons over HiRISE)"))
        if note:
            out["context"].append(_row("terrain_safety", note, "context",
                                       "H2G2 team classification", "",
                                       "terrain.geojson (polygons over HiRISE)"))
    if inside:
        rows.append(_row("name", "Gale Crater · Mount Sharp (Aeolis Mons)", "context", None,
                         GAZETTEER))
    elif out["message"]:
        out["message"] += " and the point is outside the boxwork window"
    out["rows"] = [r for r in rows if r]
    out["context"] = [r for r in out["context"] if r]
    out["sources"] = [{"section": r["section"], "url": r["source_url"], "file": r["source_file"]}
                      for r in out["rows"] + out["context"]]
    return out
