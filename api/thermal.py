"""Thermal inertia (THEMIS, quantitative, 100 m/px) -- colored layer and
value at the point. File generated by data-pipeline/scripts/fetch_themis_ti.py.

High TI = material that holds heat (exposed rock, cemented soil);
low TI = loose material (sand, dust). Only this qualitative reading is
given here: numeric class cutoffs would require a citation (Fergason et al.
2006) and stay out until verified."""

import functools
import os
import sqlite3

import numpy as np
import rasterio

UNIT = "J m⁻² K⁻¹ s⁻½"
SOURCE = "Mars Odyssey THEMIS · quantitative global thermal inertia mosaic (USGS Astropedia), 100 m/px"

#: fixed color scale range (covers 260–503 of the boxwork crop with margin);
#: fixed so the color means the same value in any tile
TI_MIN, TI_MAX = 200.0, 550.0
#: same color stops as the legend in web/layers.js
COLOR_STOPS = ((0.0, (40, 30, 90)), (0.35, (60, 110, 190)), (0.65, (240, 200, 70)), (1.0, (220, 70, 40)))


def _color(t: np.ndarray) -> np.ndarray:
    """t in [0,1] -> (3, ...) uint8 by linear interpolation between COLOR_STOPS."""
    xs = [p for p, _ in COLOR_STOPS]
    return np.stack([np.interp(t, xs, [c[i] for _, c in COLOR_STOPS]) for i in range(3)]).astype("uint8")


@functools.lru_cache(maxsize=1)
def ti_grid_rgba(path: str):
    """(rgba[4,h,w], transform, crs) -- no data becomes a transparent pixel."""
    with rasterio.open(path) as ds:
        ti = ds.read(1).astype("float64")
        nodata, transform, crs = ds.nodata, ds.transform, ds.crs
    valid = np.isfinite(ti) if nodata is None else (ti != nodata) & np.isfinite(ti)
    t = np.clip((np.where(valid, ti, TI_MIN) - TI_MIN) / (TI_MAX - TI_MIN), 0, 1)
    rgba = np.zeros((4, *ti.shape), dtype="uint8")
    rgba[:3] = _color(t)
    rgba[3] = np.where(valid, 255, 0)
    return rgba, transform, crs


def inertia_at_point(conn: sqlite3.Connection, lat: float, lon: float) -> dict | None:
    """TI value in the 100 m cell that contains the point, or None (no data)."""
    row = conn.execute(
        "SELECT local_tile_path FROM raster_registry WHERE access_type = 'thermal_scalar'"
        " AND min_lon <= ? AND ? <= max_lon AND min_lat <= ? AND ? <= max_lat",
        (lon, lon, lat, lat),
    ).fetchone()
    if row is None or not os.path.isfile(row["local_tile_path"]):
        return None
    with rasterio.open(row["local_tile_path"]) as ds:
        r, c = ds.index(lon, lat)
        if not (0 <= r < ds.height and 0 <= c < ds.width):
            return None
        v = float(ds.read(1)[r, c])
        if (ds.nodata is not None and v == ds.nodata) or not np.isfinite(v):
            return None
    return {"value": round(v), "unit": UNIT, "resolution_m": 100, "source": SOURCE, "confidence": "measured"}
